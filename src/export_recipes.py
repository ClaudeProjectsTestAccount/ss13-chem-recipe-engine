"""export_recipes.py - run the verified recipes (recipes.py) through the engine and write docs/RECIPES.md.
    python3 src/export_recipes.py            # rewrites docs/RECIPES.md
"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import chemlib, chemcli, search, planner
from recipes import RECIPES, EXTRA, NOT_DISPENSER_ONLY

HARM = {'safe': 'harmless', 'caution': 'use with care', 'danger': 'dangerous: Law 1 applies'}

def _steps(rig):
    out = []
    for i, st in enumerate(rig.steps, 1):
        text = st['text'].replace('<--', '**<--').replace('TRIGGER', 'TRIGGER**') if '<--' in st['text'] else st['text']
        out.append('%d. %s  \n   `beaker: %s | syringe: %s`' % (i, text, st['beaker'], st['syringe']))
    return out

def _order(v):
    return 'any dispense order gives this result.' if v['perm_same'] == v['perm_total'] else \
        'ORDER MATTERS - %d of %d dispense orders work; follow the steps exactly.' % (v['perm_same'], v['perm_total'])

def result_lines(db, rig, payload):
    """one line per effect, computed by the engine"""
    R = db.find_reagent
    lines = []
    foams = [e for e in rig.sim.effects if e['kind'] == 'foam']
    smokes = [e for e in rig.sim.effects if e['kind'] == 'smoke']
    if foams:
        tiles = sum(e['tiles'] for e in foams)
        tile = foams[0]['tile']
        held = ', '.join('%gu %s' % (round(x, 1), db.name(p)) for p, x in tile.items()) or 'nothing (the foam only leaves its structure)'
        l = 'Foam over up to %d tiles, each tile holds %s.' % (tiles, held)
        if payload and len(foams) == 1:
            m = search.foam_metrics(rig, R(payload))
            if m: l += ' Every %.1fs tick exposes the floor to %.1fu of %s per tile (%d ticks).' % (search.FOAM_DT, m['per_call'], db.name(R(payload)), m['calls'])
        lines.append(l)
    for e in smokes:
        l = 'Smoke over up to %d tiles, each tile holds %s.' % (e['tiles'], ', '.join('%gu %s' % (round(x, 1), db.name(p)) for p, x in e['tile'].items()))
        if payload:
            m = search.smoke_metrics(rig, R(payload))
            if m: l += ' Every %.1fs tick a mob in the tile breathes in a share of that: %.1fu of %s per tick (%d ticks over the 20s life).' % (search.SMOKE_DT, m['per_call'], db.name(R(payload)), m['calls'])
        lines.append(l)
    for e in rig.sim.effects:
        if e['kind'] == 'vortex':
            lines.append('Vortex (%s) with range %.1f tiles%s.' % (e['mode'], e['range'], ' (the formula gave %.1f, capped at %g)' % (e['raw_range'], e['cap']) if e['raw_range'] > e['cap'] else ''))
        elif e['kind'] == 'mobspawn':
            lines.append('Spawns rand(1,%d) %smobs.' % (e['max'], 'friendly ' if e['friendly'] else ''))
        elif e['kind'] == 'UNMODELED':
            lines.append('UNMODELED effect: %s' % e)
    return lines

def gear_of(spec):
    return planner.Gear(spec.get('beaker', 'large'), spec.get('syringe', 'standard'), spec.get('trigger_beaker'))

def needs(r, gear):
    n = []
    if gear.beaker != 100: n.append('beaker: %s (%gu)' % (gear.bname, gear.beaker))
    if gear.syringe != 15 and not gear.two: n.append('syringe: %s (%gu)' % (gear.sname, gear.syringe))
    if any(o[0] == 'heat' for o in r['ops']): n.append('a chem heater')
    for o in r['ops']:
        if o[0] == 'add': n.append('outside supply: %gu %s' % (o[2], o[1]))
    return n

def build():
    db = chemlib.DB(json_path=os.path.join(HERE, 'chemdata.json')); R = db.find_reagent
    md = ['# Verified medborg chem recipes', '',
          'Generated by `src/export_recipes.py` from the engine (tier-1 chem dispenser; gear is stated per recipe, default = 15u syringe + 100u large beaker). '
          'Rules snapshot: Monkestation2.0 commit `%s`. Not yet tested in-game.' % db.meta.get('commit', '?')[:10], '',
          'Read each list top to bottom. "Dispenser" steps are chem dispenser clicks (the number of clicks is given), '
          '"Syringe" steps use the borg syringe. `beaker:` shows what should be in the beaker afterwards, as a sanity check.', '',
          '## Index', '',
          '| Recipe | What it does | Gear | Risk |', '|---|---|---|---|']
    idx = [('cleaner-smoke', 'Cleaner smoke', 'cleans a 45 tile cloud', 'default', 'safe'),
           ('cleaner-foam', 'Cleaner foam', 'cleans 30 tiles', 'default', 'safe'),
           ('lube-smoke', 'Lube smoke', '45 tiles of space lube', 'default', 'caution'),
           ('lube-foam', 'Lube foam', '30 tiles of space lube', 'default', 'caution'),
           ('hellfoam', 'Hellfoam', 'fluorosulfuric acid foam', 'default + heater', 'danger')]
    for r in EXTRA:
        g = gear_of(r['gear'])
        rig = chemcli._run(db, r['ops'], 1, False, g)
        idx.append((r['key'], r['title'], r['short'], ', '.join(needs(r, g)) or 'default', r['harm']))
    anchor = lambda t: re.sub(r'[^a-z0-9 _-]', '', t.lower()).replace(' ', '-')
    orig_titles = {k: t for k, t, _, _ in RECIPES}
    for k, t, w, g, h in idx:
        full = orig_titles.get(k, t)
        md.append('| [%s](#%s) | %s | %s | %s |' % (t if k not in orig_titles else t, anchor(full), w, g, HARM[h]))
    md.append('')
    md.append('## Original recipes'); md.append('')
    for key, title, payload, ops in RECIPES:
        rig = chemcli._run(db, ops, 1, False)
        v = chemcli.verify_orders(db, ops, 1)
        eff = [e for e in rig.sim.effects if e['kind'] in ('foam', 'smoke')][0]
        m = (search.foam_metrics if eff['kind'] == 'foam' else search.smoke_metrics)(rig, R(payload))
        md.append('### ' + title); md.append('')
        md.extend(_steps(rig))
        tile = ', '.join('%gu %s' % (x, db.name(p)) for p, x in eff['tile'].items())
        md.append('')
        md.append('**Result:** %s over %d tiles, each tile holds %s. Every %.1fs tick exposes the floor to %.1fu of %s per tile (%d ticks).' % (
            eff['kind'], eff['tiles'], tile, search.FOAM_DT if eff['kind'] == 'foam' else search.SMOKE_DT, m['per_call'], db.name(R(payload)), m['calls']))
        md.append('')
        md.append('**Order:** ' + _order(v))
        md.append('')
    md.append('## New reactions'); md.append('')
    md.append('A second batch, picked from the reaction list for effects people do not usually know about, several of which need bigger beakers or '
              'syringes. The effect text is taken from the game code (file names in each `Source` line); the numbers in `Result` come from the engine. '
              'Foam is slippery for its 8 s life (`AddComponent(/datum/component/slippery, 100)` in `effects_foam.dm`), whatever the payload.')
    md.append('')
    for r in EXTRA:
        g = gear_of(r['gear'])
        rig = chemcli._run(db, r['ops'], 1, False, g)
        v = chemcli.verify_orders(db, r['ops'], 1, g)
        md.append('### ' + r['title']); md.append('')
        md.append('**Risk:** %s.  **Needs:** %s.' % (HARM[r['harm']], '; '.join(needs(r, g)) or 'default gear (15u syringe, 100u large beaker)'))
        md.append('')
        md.append('**What it does:** ' + r['what']); md.append('')
        md.extend(_steps(rig)); md.append('')
        for l in result_lines(db, rig, r.get('payload')): md.append('**Result:** ' + l); md.append('')
        md.append('**Notes:** ' + r['how']); md.append('')
        md.append('**Caution:** ' + r['caution']); md.append('')
        md.append('**Order:** ' + _order(v)); md.append('')
        if rig.sim.warnings: md.append('Engine warnings: ' + '; '.join(rig.sim.warnings) + ' (expected where the recipe relies on the dispenser stopping at the free space).'); md.append('')
        md.append('Source: `%s`' % r['src']); md.append('')
    md.append('## Interesting reactions the dispenser alone cannot make'); md.append('')
    md.append('The planner (`decompose`) cannot reach these from dispenser chemicals; each needs ingredients with no recipe (nutriment, omnizine, holy water, '
              'triple citrus...) or blood, supplied by someone else:'); md.append('')
    for k, n, d in NOT_DISPENSER_ONLY: md.append('- **%s** (`%s`): %s' % (n, k, d))
    md.append('')
    return '\n'.join(md)

if __name__ == '__main__':
    out = os.path.join(os.path.dirname(HERE), 'docs', 'RECIPES.md')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w') as fh: fh.write(build())
    print('wrote', out)
